fn image(planar: bool) -> Image {
    let samples = if planar {
        let mut y = vec![255u8; 256];
        for yy in 0..11 {
            for x in 0..13 {
                y[yy * 16 + x] = u8::try_from(20 + (x * 7 + yy * 11) % 210).unwrap();
            }
        }
        Samples::Planar(Box::new(
            Planar::new(
                (13, 11),
                [2, 2],
                [[2, 2, 16], [1, 1, 8], [1, 1, 8]],
                [y, vec![128; 64], vec![128; 64]],
            )
            .unwrap(),
        ))
    } else {
        Samples::Bytes(
            (0..11)
                .flat_map(|y| {
                    (0..13).flat_map(move |x| {
                        (0..3).map(move |c| u8::try_from((x * 31 + y * 47 + c * 53) % 256).unwrap())
                    })
                })
                .collect(),
        )
    };
    Image {
        decoded: DecodedImage {
            width: 13,
            height: 11,
            bits_per_component: 8,
            components: 3,
            samples,
            kind: ImageKind::Color { color_space: None },
            decode: None,
            mask: MaskKind::None,
            interpolate: false,
            reduction: None,
        },
        space: Some(Space::Rgb),
        mask: None,
        matte: None,
        decode: vec![(0.0, 1.0); 3],
        intent: None,
    }
}
#[test]
fn planar_and_byte_samples_with_turns_and_fractional_coverage_stay_within_one_level() {
    for planar in [false, true] {
        let image = image(planar);
        let samples = if let Samples::Bytes(v) = &image.decoded.samples {
            v.as_slice()
        } else {
            &[]
        };
        for case in CASES {
            let [a, b, c, d, e, f] = case.map;
            let placement = Placement {
                width: case.width,
                height: case.height,
                inverse: Transform::new(
                    a / 13.0,
                    -b / 11.0,
                    c / 13.0,
                    -d / 11.0,
                    e / 13.0,
                    1.0 - f / 11.0,
                ),
                range: [0, case.width as usize, 0, case.height as usize],
                extent: case.extent,
                rotated: case.rotated,
            };
            let actual = area::paint(
                &image,
                samples,
                &placement,
                &RenderOptions::default(),
                Limits::default(),
            )
            .unwrap();
            let expected = if planar { case.planar } else { case.raw };
            assert_eq!(actual.data().len(), expected.len());
            for (index, (&a, &b)) in actual.data().iter().zip(expected).enumerate() {
                assert!(
                    a.abs_diff(b) <= 1,
                    "planar={planar},rotation={},channel={index}: {a}/{b}",
                    case.rotated
                );
            }
        }
    }
}
#[test]
fn image_area_limits_are_checked_before_large_storage() {
    let image = image(false);
    let Samples::Bytes(data) = &image.decoded.samples else {
        unreachable!()
    };
    let p = Placement {
        width: 5,
        height: 4,
        inverse: Transform::new(0.2, 0.0, 0.0, -0.25, 0.0, 1.0),
        range: [0, 5, 0, 4],
        extent: [0.0, 5.0, 0.0, 4.0],
        rotated: false,
    };
    for limits in [
        Limits {
            decoded_bytes: 1,
            ..Limits::default()
        },
        Limits {
            raster_work: 1,
            ..Limits::default()
        },
    ] {
        assert!(area::paint(&image, data, &p, &RenderOptions::default(), limits).is_err());
    }
}
