"""Generate the SASLprep membership ranges of RFC 3454 Appendices A-D.

    python3 tools/gen/saslprep.py [--rfc PATH] [--check]

The tables are RFC 3454's. With --rfc, the appendices are read from a local
copy of the RFC (pinned by SHA-256; no downloads) and every code point is
checked against Python's Unicode 3.2 `stringprep` predicates. Without it, the
same membership comes from those predicates alone, so `tools/check.py` can
verify the generated file without the RFC text. --check validates without
writing. The output holds merged numeric ranges, not RFC prose.
"""
from __future__ import annotations

import argparse
import re
import stringprep
from array import array
from collections.abc import Callable
from hashlib import sha256
from pathlib import Path

TABLES = ("A.1", "B.1", "C.1.2", "C.2.1", "C.2.2", "C.3", "C.4", "C.5", "C.6", "C.7", "C.8", "C.9", "D.1", "D.2")
RFC_SHA256 = "eb722fa698fb7e8823b835d9fd263e4cdb8f1c7b0d234edf7f0e3bd2ccbb2c79"
CODE_POINTS = 0x110000
ROOT = Path(__file__).resolve().parents[2]
OUTPUT = ROOT / "crates/pagura-crypto/src/standard/saslprep/tables.rs"


def predicate(table: str) -> Callable[[str], bool]:
    return getattr(stringprep, "in_table_" + table.lower().replace(".", ""))


def from_predicates() -> array[int]:
    result = array("H", [0]) * CODE_POINTS
    for index, table in enumerate(TABLES):
        member = predicate(table)
        for code in range(CODE_POINTS):
            if member(chr(code)):
                result[code] |= 1 << index
    return result


def from_rfc(text: str) -> array[int]:
    result = array("H", [0]) * CODE_POINTS
    for index, table in enumerate(TABLES):
        start = f"----- Start Table {table} -----"
        end = f"----- End Table {table} -----"
        if text.count(start) != 1 or text.count(end) != 1:
            raise ValueError(f"missing or ambiguous table {table}")
        body = text.split(start, 1)[1].split(end, 1)[0]
        previous = -1
        count = 0
        for line in body.splitlines():
            field = line.split(";", 1)[0].strip()
            if not re.fullmatch(r"[0-9A-F]{4,6}(?:-[0-9A-F]{4,6})?", field):
                # RFC page headers and footers are outside the numeric grammar.
                continue
            bounds = [int(value, 16) for value in field.split("-")]
            low, high = bounds[0], bounds[-1]
            if not previous < low <= high < CODE_POINTS:
                raise ValueError(f"unsorted or overlapping table {table}")
            for code in range(low, high + 1):
                result[code] |= 1 << index
            previous = high
            count += 1
        if not count:
            raise ValueError(f"empty table {table}")
    return result


def flags(value: int) -> str:
    return " | ".join(table.replace(".", "_") for index, table in enumerate(TABLES) if value & (1 << index))


def render(values: array[int]) -> bytes:
    lines = [
        "//! RFC 3454 Appendices A-D membership ranges for SASLprep (RFC 4013).",
        "//! Generated by tools/gen/saslprep.py; do not edit. `--check` verifies it.",
        f"// RFC 3454 source SHA-256: {RFC_SHA256}",
        "",
    ]
    for index, table in enumerate(TABLES):
        lines.append(f"pub(super) const {table.replace('.', '_')}: u16 = 1 << {index};")
    lines.extend(["", "pub(super) const RANGES: &[(u32, u32, u16)] = &["])
    start = 0
    for end in range(1, CODE_POINTS + 1):
        if end < CODE_POINTS and values[end] == values[start]:
            continue
        if values[start]:
            low, high = f"{start:08x}", f"{end - 1:08x}"
            lines.append(f"    (0x{low[:4]}_{low[4:]}, 0x{high[:4]}_{high[4:]}, {flags(values[start])}),")
        start = end
    lines.append("];\n")
    return "\n".join(lines).encode()


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--rfc", type=Path, help="local copy of RFC 3454 to generate from")
    parser.add_argument("--check", action="store_true", help="verify the generated file without writing")
    args = parser.parse_args()
    values = from_predicates()
    if args.rfc:
        source = args.rfc.read_bytes()
        if sha256(source).hexdigest() != RFC_SHA256:
            raise SystemExit(f"{args.rfc} is not the pinned RFC 3454 text")
        if from_rfc(source.decode("ascii")) != values:
            raise SystemExit("RFC 3454 tables disagree with Unicode 3.2 stringprep")
    result = render(values)
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_bytes() != result:
            raise SystemExit("SASLprep tables differ; run python3 tools/gen/saslprep.py")
        print("SASLprep tables are current")
    else:
        OUTPUT.write_bytes(result)
        print(f"Generated {OUTPUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
