"""Generate numeric SASLprep membership data from RFC 3454 Appendices A-D.

Read a local reference only; no downloads. Python's Unicode 3.2 stringprep
predicates independently check every code point in every requested table.
The generated file contains merged numeric ranges, not RFC prose or comments.
"""
from __future__ import annotations

import argparse
from array import array
from hashlib import sha256
from pathlib import Path
import re
import stringprep

TABLES = ("A.1", "B.1", "C.1.2", "C.2.1", "C.2.2", "C.3", "C.4", "C.5", "C.6", "C.7", "C.8", "C.9", "D.1", "D.2")
OUTPUT = Path(__file__).resolve().parents[1] / "src/standard/saslprep/tables.rs"


def memberships(text):
    result = array("H", [0]) * 0x110000
    for index, name in enumerate(TABLES):
        start = f"----- Start Table {name} -----"
        end = f"----- End Table {name} -----"
        if text.count(start) != 1 or text.count(end) != 1:
            raise ValueError(f"missing or ambiguous table {name}")
        body = text.split(start, 1)[1].split(end, 1)[0]
        previous = -1
        count = 0
        for line in body.splitlines():
            field = line.split(";", 1)[0].strip()
            if not re.fullmatch(r"[0-9A-F]{4,6}(?:-[0-9A-F]{4,6})?", field):
                # RFC page headers and footers are outside the numeric grammar.
                continue
            bounds = [int(value, 16) for value in field.split("-")]
            low, high = bounds[0], bounds[-1]
            if not previous < low <= high <= 0x10ffff:
                raise ValueError(f"unsorted or overlapping table {name}")
            for code in range(low, high + 1):
                result[code] |= 1 << index
            previous = high
            count += 1
        if not count:
            raise ValueError(f"empty table {name}")
        oracle = getattr(stringprep, "in_table_" + name.lower().replace(".", ""))
        for code, flags in enumerate(result):
            if bool(flags & (1 << index)) != oracle(chr(code)):
                raise ValueError(f"table {name} disagrees with stringprep at U+{code:04X}")
    return result


def render(source):
    values = memberships(source.decode("ascii"))
    lines = [
        "//! Numeric RFC 3454 Appendices A-D membership ranges for SASLprep (RFC 4013).",
        "//! Generated by crates/pagura-crypto/tools/generate_stringprep.py; do not edit.",
        "//! Reproduce with --rfc PATH; --check validates without writing.",
        f"// RFC 3454 source SHA-256: {sha256(source).hexdigest()}",
        "",
    ]
    for index, table in enumerate(TABLES):
        lines.append(f"pub(super) const {table.replace('.', '_')}: u16 = 1 << {index};")
    lines.extend(["", "pub(super) const RANGES: &[(u32, u32, u16)] = &["])
    start = 0
    for end in range(1, len(values) + 1):
        if end < len(values) and values[end] == values[start]:
            continue
        if values[start]:
            lo, hi = f"{start:08x}", f"{end-1:08x}"
            lines.append(f"    (0x{lo[:4]}_{lo[4:]}, 0x{hi[:4]}_{hi[4:]}, 0x{values[start]:04x}),")
        start = end
    lines.append("];\n")
    return "\n".join(lines).encode()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--rfc", type=Path, required=True)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = render(args.rfc.read_bytes())
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_bytes() != result:
            raise SystemExit("Generated stringprep tables differ")
        print("Verified RFC tables and Rust output against Unicode 3.2 stringprep")
    else:
        OUTPUT.write_bytes(result)
        print("Generated RFC tables; every membership agrees with Unicode 3.2 stringprep")


if __name__ == "__main__":
    main()
