"""Generate bounded NFKC tables from the pinned Unicode 3.2 data only.

Run with --check to verify reproducibility. Python's Unicode implementation is
not used to construct these tables; it is an independent fixture oracle.
"""
import argparse
import hashlib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "data/unicode"
OUTPUT = ROOT / "crates/pagura-crypto/src/standard/saslprep/normalization/tables.rs"
INPUTS = ("UnicodeData-3.2.0-normalization.txt", "CompositionExclusions-3.2.0.txt",
          "DerivedNormalizationProps-3.2.0-nfkc.txt", "NormalizationCorrections-3.2.0.txt")


def records(name):
    for line in (DATA / name).read_text().splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            yield [field.strip() for field in line.split(";")]


def points(field):
    endpoints = field.split("..")
    return range(int(endpoints[0], 16), int(endpoints[-1], 16) + 1)


def ranges(values):
    result = []
    for code in sorted(values):
        if result and result[-1][1] + 1 == code:
            result[-1] = (result[-1][0], code)
        else:
            result.append((code, code))
    return result


def scalar(code):
    assert 0 <= code <= 0x10ffff and not 0xd800 <= code <= 0xdfff
    return f"'\\u{{{code:x}}}'"


def generate():
    classes, decompositions, canonical = {}, {}, {}
    for fields in records(INPUTS[0]):
        code, combining = int(fields[0], 16), int(fields[3])
        if combining:
            classes[code] = combining
        decomposition = fields[5].split()
        if decomposition:
            compatibility = decomposition[0].startswith("<")
            sequence = tuple(int(value, 16) for value in decomposition[compatibility:])
            decompositions[code] = sequence
            if not compatibility:
                canonical[code] = sequence
    explicit = {code for fields in records(INPUTS[1]) for code in points(fields[0])}
    properties = {}
    for fields in records(INPUTS[2]):
        properties.setdefault(fields[1], set()).update(points(fields[0]))
    excluded = properties["Full_Composition_Exclusion"]
    # UAX #15: primary exclusions, singletons and decompositions beginning
    # with a nonstarter comprise the complete composition exclusion set.
    derived = explicit | {code for code, seq in canonical.items()
                          if len(seq) == 1 or classes.get(seq[0], 0)}
    assert excluded == derived
    for fields in records(INPUTS[3]):
        code, corrected = int(fields[0], 16), int(fields[2], 16)
        assert tuple(map(int, fields[3].split("."))) <= (3, 2, 0)
        assert decompositions[code] == (corrected,)

    def expand(code, active=()):
        assert code not in active
        if 0xac00 <= code < 0xd7a4:
            index = code - 0xac00
            return (0x1100 + index // 588, 0x1161 + index % 588 // 28) + ((0x11a7 + index % 28,) if index % 28 else ())
        if code not in decompositions:
            return (code,)
        return tuple(item for child in decompositions[code] for item in expand(child, active + (code,)))

    pool, offsets, entries = bytearray(), {}, []
    for code in sorted(decompositions):
        sequence = expand(code)
        encoded = "".join(map(chr, sequence)).encode()
        if encoded not in offsets:
            offsets[encoded] = len(pool)
            pool.extend(encoded)
        assert len(pool) <= 65535 and len(encoded) <= 255
        entries.append((code, offsets[encoded], len(encoded)))
    combining_ranges = []
    for code, value in sorted(classes.items()):
        if combining_ranges and combining_ranges[-1][1] + 1 == code and combining_ranges[-1][2] == value:
            combining_ranges[-1] = (combining_ranges[-1][0], code, value)
        else:
            combining_ranges.append((code, code, value))
    compositions = sorted((seq[0], seq[1], code) for code, seq in canonical.items()
                          if len(seq) == 2 and code not in excluded)
    assert len({(a, b) for a, b, _ in compositions}) == len(compositions)
    quick = ranges(properties["NFKC_NO"] | properties["NFKC_MAYBE"])
    lines = ["// Generated by python3 tools/fixturegen/unicode32.py; do not edit.",
             "// Unicode 3.2.0 NFKC; RFC 3454 sections 4 and 8.1 (UAX #15 revision 22).",
             "// F951 uses its 3.2.0 correction; later-version corrections are not applied."]
    for name in INPUTS:
        lines.append(f"// {name}: SHA-256 {hashlib.sha256((DATA / name).read_bytes()).hexdigest()}")
    lines += ["//", *["// " + line if line else "//" for line in (DATA / "LICENSE").read_text().splitlines()], ""]
    lines += ["pub(super) const DECOMPOSITIONS: &[(char, u16, u8)] = &["]
    lines += [f"    ({scalar(code)}, {offset}, {length})," for code, offset, length in entries]
    lines += ["];", "", "pub(super) const TEXT: &str = concat!("]
    characters = list(pool.decode())
    lines += ['    "' + "".join(f"\\u{{{ord(ch):x}}}" for ch in characters[i:i+8]) + '",' for i in range(0, len(characters), 8)]
    lines += [");", "", "pub(super) const COMBINING: &[(u32, u32, u8)] = &["]
    code_literal = lambda code: f"0x{code >> 16:04x}_{code & 65535:04x}"
    lines += [f"    ({code_literal(a)}, {code_literal(b)}, {value})," for a, b, value in combining_ranges]
    lines += ["];", "", "pub(super) const COMPOSITIONS: &[(char, char, char)] = &["]
    lines += [f"    ({scalar(a)}, {scalar(b)}, {scalar(c)})," for a, b, c in compositions]
    lines += ["];", "", "pub(super) const QUICK_CHECK: &[(u32, u32)] = &["]
    lines += [f"    ({code_literal(a)}, {code_literal(b)})," for a, b in quick]
    lines += ["];", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if OUTPUT.read_text() != generated:
            raise SystemExit("Unicode 3.2 normalization tables differ; regenerate them")
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_text(generated)


if __name__ == "__main__":
    main()
